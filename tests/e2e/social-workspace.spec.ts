import { test, expect } from '@playwright/test';

test('local social workspace offers separate announcements and retrospectives without public navigation', async ({ page }) => {
  await page.goto('/__social/');
  await expect(page.getByRole('heading', { name: 'Social-Werkstatt', exact: true })).toBeVisible();
  await expect(page.locator('#event')).toBeEnabled();
  await expect(page.locator('#load')).toHaveCSS('min-height', '44px');
  const event = page.getByRole('button', { name: 'Event', exact: true });
  await expect(event).toHaveCSS('min-height', '44px');
  await event.click();
  const search = page.getByRole('searchbox', { name: 'Auswahl filtern' });
  await expect(search).toBeFocused();
  await search.fill('kein-treffer-xyz');
  await expect(page.getByText('Keine Treffer gefunden.')).toBeVisible();
  await search.fill('thundermother');
  const option = page.getByRole('option', { name: '2027-02-21 · Thundermother' });
  await expect(option).toBeVisible();
  await option.click();
  await expect(event).toContainText('Thundermother');
  await expect(page.locator('#event')).toBeEnabled();
  await expect(page.locator('#images')).toContainText('2027-02-21_00-00-00.jpg');
  const phase = page.getByRole('button', { name: 'Phase', exact: true });
  await phase.click();
  await search.press('Escape');
  await expect(phase).toBeFocused();
  await phase.click();
  await search.fill('Rückblick');
  await expect(page.getByRole('option')).toHaveCount(1);
  await search.press('ArrowDown');
  await page.keyboard.press('Enter');
  await expect(phase).toContainText('Rückblick');
  await expect(page.locator('#phase')).toBeEnabled();
  await expect(page.locator('#lead')).toHaveValue('');
  await expect(page.locator('#images input:checked')).toHaveCount(0);
  await page.goto('/events/2027/2027-02-21/');
  await expect(page.locator('a[href*="/__social"]')).toHaveCount(0);
  await expect(page.getByText('Social-Werkstatt', { exact: true })).toHaveCount(0);
});
